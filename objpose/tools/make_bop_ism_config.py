#!/usr/bin/env python3
"""make_bop_ism_config.py — write sam6d_realtime/configs/yolo_ism_<dataset>.yaml for a BOP dataset.

Takes the operating point of the lab config (configs/yolo_ism_objects.yaml) and re-points it
at the 21 YCB-V objects. Two of the lab config's gates are switched OFF here on purpose:

  hsv_gate_enabled          the 0.1214 threshold was fitted on the 10 lab objects' renders;
                            nothing has been fitted on YCB-V, so keeping it on would reject
                            on an unvalidated constant.
  training_free_gate        already off in the lab config; kept off.

Everything else (appe-v2 blocks 2+9 at 0.605, cross-object NMS, similarity 0.35) is left at
the lab operating point so the two datasets are run by the same recogniser.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "sam6d_realtime" / "configs" / "yolo_ism_objects.yaml"

HEADER = """# yolo_ism_{ds}.yaml — BOP {ds} ({n} objects), generated by objpose/tools/make_bop_ism_config.py
#
# Same recogniser operating point as configs/yolo_ism_objects.yaml, with the HSV colour gate
# OFF: its threshold (0.1214) was fitted on the lab objects and nothing has been fitted on
# this dataset. Templates are the 42-view CPU renders of its obj_*.ply
# (objpose/tools/render_bop_templates.sh); PEM assets come from
# objpose/tools/build_bop_assets.py.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--table", default=str(REPO / "objpose" / "rt" / "bop" / "ycbv_objects.json"))
    a = ap.parse_args()
    table = json.loads(Path(a.table).read_text())
    ds = table["dataset"]
    models = Path(table["models_dir"])
    out = REPO / "sam6d_realtime" / "configs" / f"yolo_ism_{ds}.yaml"
    defaults = dict(yaml.safe_load(SRC.read_text(encoding="utf-8"))["defaults"])
    defaults["hsv_gate_enabled"] = False
    defaults["hsv_gate_shadow_mode"] = False
    # per-dataset operating-point changes, recorded in the table so a config is reproducible
    overrides = dict(table.get("ism_overrides", {}))
    defaults.update(overrides)

    objs = []
    for o in table["objects"]:
        objs.append({
            "name": o["name"],
            "yolo_prompt": o["prompt"],
            "object_id": o["name"],
            "template_dir": f"template/{o['name']}/templates",
            "cad_ply": str(models / f"obj_{o['obj_id']:06d}.ply"),
            "enabled": True,
        })
    head = HEADER.format(ds=ds, n=len(objs))
    if overrides:
        head += ("#\n# Per-dataset overrides from the table (rt/bop/%s_objects.json):\n%s"
                 % (ds, "".join(f"#   {k}: {v}\n" for k, v in overrides.items())))
    out.write_text(head + yaml.safe_dump({"defaults": defaults, "objects": objs},
                                         sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"[make_bop_ism_config] {ds}: {len(objs)} objects -> {out}")


if __name__ == "__main__":
    main()
